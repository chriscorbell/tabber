import AppKit
import Testing
@testable import TabberInput

@Suite struct PasteboardRoundTrip {
    @Test func restoresEveryItemAndType() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }

        let custom = NSPasteboard.PasteboardType("com.example.tabber-test")
        let first = NSPasteboardItem()
        first.setString("hello", forType: .string)
        first.setData(Data("<b>hello</b>".utf8), forType: .html)
        first.setData(Data([0, 1, 2, 255]), forType: custom)
        let second = NSPasteboardItem()
        second.setString("https://example.com", forType: .URL)
        second.setString("second", forType: .string)
        pasteboard.clearContents()
        #expect(pasteboard.writeObjects([first, second]))

        let saved = PasteboardSnapshot.capture(pasteboard)
        #expect(saved.items.count == 2)

        let ours = PasteboardMarker.writeTransient(" world", to: pasteboard)
        #expect(pasteboard.changeCount == ours)
        #expect(pasteboard.string(forType: .string) == " world")
        #expect(pasteboard.types?.contains(PasteboardMarker.transient) == true)
        #expect(pasteboard.types?.contains(PasteboardMarker.autoGenerated) == true)

        saved.restore(to: pasteboard)
        #expect(PasteboardSnapshot.capture(pasteboard) == saved)
        let items = try #require(pasteboard.pasteboardItems)
        #expect(items.count == 2)
        #expect(items[0].string(forType: .string) == "hello")
        #expect(items[0].data(forType: custom) == Data([0, 1, 2, 255]))
        #expect(items[1].string(forType: .URL) == "https://example.com")
        #expect(pasteboard.types?.contains(PasteboardMarker.transient) == false)
    }

    @Test func restoresAnEmptyPasteboard() {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        let saved = PasteboardSnapshot.capture(pasteboard)
        #expect(saved.items.isEmpty)
        PasteboardMarker.writeTransient("x", to: pasteboard)
        saved.restore(to: pasteboard)
        #expect((pasteboard.pasteboardItems ?? []).isEmpty)
    }
}
