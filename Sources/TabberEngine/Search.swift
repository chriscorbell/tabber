import Accelerate
import Foundation
import TabberCore
import llama

/// Decoding: a small beam picks the most likely complete first word, then greedy decoding extends it.
///
/// Why: the first word is what the user accepts most often, and when they are mid-word the most likely
/// first token often leads to a less likely word ("fl" → "fl|ight" vs "fl|aky"). Scoring complete words,
/// including the probability that the word ends there, picks better first words. After that, short
/// greedy continuations are both fast and good enough, and get cut when the model hesitates.
extension LlamaEngine {
    struct SearchOutcome {
        var text: String
        var stop: CompletionResult.StopReason
        var meanLogProb: Double
        var firstWordLogProb: Double
        var alternatives: [String]
        var firstTokenMs: Double
        var generatedTokens: Int
    }

    private struct Branch {
        var seq: Int32
        var tokens: [llama_token] = []
        /// Generated bytes, starting with the required (healed) bytes.
        var bytes: [UInt8] = []
        var score: Double = 0
        var remaining: ArraySlice<UInt8>
        /// Output row holding this branch's next-token logits. -1 is the last output.
        var row: Int32 = -1
    }

    private struct Finished {
        var tokens: [llama_token]
        var bytes: [UInt8]
        var score: Double
        /// Set when the text ends for good here (end of text, line break) rather than at a word boundary.
        var stop: CompletionResult.StopReason?
    }

    private struct Distribution {
        var logits: UnsafeMutablePointer<Float>
        var lse: Double
        /// Probability that the next token starts a new word, ends the line, or ends the text.
        var breakMass: Double
        var eogMass: Double
        func logProb(_ t: Int32) -> Double { Double(logits[Int(t)]) - lse }
    }

    private func distribution(row: Int32, bias: [Int32: Float]) throws -> Distribution {
        guard var logits = llama_get_logits_ith(ctx, row) else { throw CompletionError.decodeFailed(-1) }
        let n = table.count
        if !bias.isEmpty {
            // Work on a copy so the same row can be read again without biasing it twice.
            logitScratch.update(from: logits, count: n)
            logits = logitScratch
            for (t, b) in bias { logits[Int(t)] += b }
        }
        var maxLogit: Float = 0
        vDSP_maxv(logits, 1, &maxLogit, vDSP_Length(n))
        var sum: Double = 0, breakSum: Double = 0, eogSum: Double = 0
        let breaks = table.startsWithBreak, eog = table.isEOG
        for t in 0..<n {
            let e = Double(expf(logits[t] - maxLogit))
            sum += e
            if breaks[t] { breakSum += e } else if eog[t] { eogSum += e }
        }
        return Distribution(logits: logits, lse: Double(maxLogit) + Foundation.log(sum), breakMass: (breakSum + eogSum) / sum, eogMass: eogSum / sum)
    }

    /// Best `k` token ids by logit, among those passing `allowed`.
    private func topTokens(_ d: Distribution, k: Int, allowed: (Int) -> Bool) -> [Int32] {
        var best: [(Int32, Float)] = []
        best.reserveCapacity(k + 1)
        var floor = -Float.infinity
        for t in 0..<table.count where d.logits[t] > floor && allowed(t) {
            best.append((Int32(t), d.logits[t]))
            if best.count > k {
                best.sort { $0.1 > $1.1 }
                best.removeLast()
                floor = best.last!.1
            }
        }
        return best.sorted { $0.1 > $1.1 }.map(\.0)
    }

    /// Likely next words that are a single token (" plan", " details"), best first, excluding the top choice.
    /// Single-token words are common words in these vocabularies, so this needs no extra decoding.
    private func wholeWordAlternatives(_ d: Distribution) -> [String] {
        let candidates = topTokens(d, k: 8, allowed: { self.table.generatable[$0] && self.table.startsWithSpace[$0] })
        var words: [String] = []
        for t in candidates.dropFirst() where exp(d.logProb(t)) >= 0.03 {
            let text = String(decoding: table.bytes[Int(t)], as: UTF8.self)
            let word = text.dropFirst()
            guard word.count >= 2, word.allSatisfy({ $0.isLetter || $0 == "'" }) else { continue }
            words.append(text)
            if words.count == 3 { break }
        }
        return words
    }

    private func hasWordCharacter(_ bytes: ArraySlice<UInt8>) -> Bool {
        String(decoding: bytes, as: UTF8.self).contains { TextRules.isWordCharacter($0) }
    }

    /// True when the text ends where a line break is natural: after sentence or clause punctuation, or a break.
    static func endsClause(_ text: String) -> Bool {
        guard let last = text.last(where: { $0 != " " && $0 != "\t" }) else { return true }
        return last.isNewline || ".!?:;,…)]\"”".contains(last)
    }

    func searchCompletion(request: CompletionRequest, plan: Plan, ticket: UInt64, onPartial: (@Sendable (String) -> Void)?) throws -> SearchOutcome {
        let start = DispatchTime.now()
        let promptLen = cached.count
        let width = info.isRecurrentOrHybrid ? 1 : max(1, config.beamWidth)
        let bias = wordBiasTokens(request.wordBias)
        let required = plan.required
        // The user is mid-word when the healed bytes end in a word character.
        let partialWord = String(decoding: required, as: UTF8.self).last.map(TextRules.isWordCharacter) ?? false
        let mem = llama_get_memory(ctx)
        var generated = 0

        // MARK: Phase A — choose the first word.

        var beams = [Branch(seq: 0, remaining: required[...])]
        var finished: [Finished] = []
        let maxSteps = 6 + required.count / 2

        var exhausted = false
        for _ in 0..<maxSteps {
            guard isCurrent(ticket) else { throw CompletionError.cancelled }
            var children: [(parent: Int, token: Int32, score: Double)] = []

            for (i, b) in beams.enumerated() {
                let d = try distribution(row: b.row, bias: bias)
                let visible = b.bytes.dropFirst(required.count)
                let wordStarted = b.remaining.isEmpty && (partialWord || hasWordCharacter(visible))

                if !b.remaining.isEmpty {
                    // Still owing typed bytes: only tokens consistent with them.
                    var cands: [(Int32, Double)] = []
                    table.forEachConsistent(with: b.remaining) { t in cands.append((t, d.logProb(t))) }
                    cands.sort { $0.1 > $1.1 }
                    // Inside the typed prefix any admissible token may lead to the right word; only drop the hopeless.
                    let bestLP = cands.first?.1 ?? 0
                    for (j, c) in cands.prefix(width).enumerated() where j == 0 || c.1 - bestLP >= Foundation.log(1e-10) {
                        children.append((i, c.0, b.score + c.1))
                    }
                } else if wordStarted {
                    // The word may end here.
                    if d.breakMass > 1e-6 {
                        finished.append(Finished(tokens: b.tokens, bytes: b.bytes, score: b.score + Foundation.log(d.breakMass), stop: nil))
                    }
                    let k = width
                    for t in topTokens(d, k: k, allowed: { self.table.generatable[$0] && !self.table.startsWithBreak[$0] }) {
                        let lp = d.logProb(t)
                        if exp(lp) >= config.minBranchProb { children.append((i, t, b.score + lp)) }
                    }
                } else {
                    // Nothing visible yet: the next token starts the first word.
                    if d.eogMass > 0.5 {
                        finished.append(Finished(tokens: b.tokens, bytes: b.bytes, score: b.score + Foundation.log(d.eogMass), stop: .endOfText))
                    }
                    for (j, t) in topTokens(d, k: width, allowed: { self.table.generatable[$0] }).enumerated() {
                        let lp = d.logProb(t)
                        if j == 0 || exp(lp) >= config.minBranchProb { children.append((i, t, b.score + lp)) }
                    }
                }
            }

            // Scores only fall as tokens are added, so a finished word that beats every open branch is final.
            let bestFinished = finished.map(\.score).max() ?? -.infinity
            children.removeAll { $0.score <= bestFinished }
            guard !children.isEmpty else { exhausted = true; break }
            children.sort { $0.score > $1.score }
            children = Array(children.prefix(width))

            // Assign sequences: the first child of a parent keeps its sequence, others get copies.
            var used = Set<Int32>()
            var next: [Branch] = []
            var freeSeqs = (0..<Int32(width + 1)).filter { s in !beams.contains { $0.seq == s } }
            let parentsWithChildren = Set(children.map(\.parent))
            for (i, b) in beams.enumerated() where !parentsWithChildren.contains(i) {
                if b.seq != 0 { llama_memory_seq_rm(mem, b.seq, -1, -1) }
                freeSeqs.append(b.seq)
            }
            for c in children {
                let parent = beams[c.parent]
                var child = parent
                if used.contains(parent.seq) {
                    guard let s = freeSeqs.first(where: { $0 != 0 && !used.contains($0) }) else { continue }
                    freeSeqs.removeAll { $0 == s }
                    llama_memory_seq_rm(mem, s, -1, -1)
                    llama_memory_seq_cp(mem, parent.seq, s, -1, -1)
                    child.seq = s
                }
                used.insert(child.seq)
                let tb = table.bytes[Int(c.token)]
                child.tokens.append(c.token)
                child.bytes.append(contentsOf: tb)
                child.score = c.score
                if !child.remaining.isEmpty { child.remaining = child.remaining.dropFirst(min(child.remaining.count, tb.count)) }
                next.append(child)
            }

            // One batch: each branch's new token on its own sequence.
            batch.n_tokens = Int32(next.count)
            for (j, b) in next.enumerated() {
                batch.token[j] = b.tokens.last!
                batch.pos[j] = Int32(promptLen + b.tokens.count - 1)
                batch.n_seq_id[j] = 1
                batch.seq_id[j]![0] = b.seq
                batch.logits[j] = 1
                next[j].row = Int32(j)
            }
            let rc = llama_decode(ctx, batch)
            guard rc == 0 else { throw CompletionError.decodeFailed(rc) }
            generated += next.count
            beams = next

            // Single branch: it may stop being "open" only by finishing, which the loop handles.
            if width == 1, finished.contains(where: { $0.score >= beams[0].score }) { break }
        }

        // The winner: the best finished word, or the best open branch if nothing finished.
        // Open branches only count when the search ran out of steps, and only once they owe no typed bytes.
        let openBest = exhausted ? nil : beams.filter { $0.remaining.isEmpty }.max { $0.score < $1.score }
        let winner: Finished
        if width == 1 {
            // Greedy: the state in the cache is the only one we can continue from without trimming.
            let current = beams[0]
            if let f = finished.last, f.tokens.count == current.tokens.count {
                winner = f
            } else if !current.remaining.isEmpty {
                return SearchOutcome(text: "", stop: .endOfText, meanLogProb: 0, firstWordLogProb: -.infinity, alternatives: [], firstTokenMs: Self.ms(since: start), generatedTokens: generated)
            } else {
                winner = Finished(tokens: current.tokens, bytes: current.bytes, score: current.score, stop: nil)
            }
        } else if let f = finished.max(by: { $0.score < $1.score }), f.score >= (openBest?.score ?? -.infinity) || openBest == nil {
            winner = f
        } else if let o = openBest {
            winner = Finished(tokens: o.tokens, bytes: o.bytes, score: o.score, stop: nil)
        } else {
            return SearchOutcome(text: "", stop: .endOfText, meanLogProb: 0, firstWordLogProb: -.infinity, alternatives: [], firstTokenMs: Self.ms(since: start), generatedTokens: generated)
        }

        // Alternatives: other complete first words, best first.
        // Alternatives describe the first word the ghost shows. When the typed word was already complete,
        // that word comes from the greedy phase, so they are filled in there instead.
        var alternatives: [String] = []
        let winnerVisible = visibleText(winner.bytes, requiredCount: required.count)
        for f in finished.sorted(by: { $0.score > $1.score }) where f.stop == nil {
            let v = visibleText(f.bytes, requiredCount: required.count)
            if !v.isEmpty, v != winnerVisible, !alternatives.contains(v) { alternatives.append(v) }
            if alternatives.count >= 3 { break }
        }

        let firstTokenMs = Self.ms(since: start)
        let firstWordLogProb = winner.score

        // Rebuild sequence 0 as prompt + winner so the cache stays canonical, and get its logits.
        for s in 1..<Int32(width + 1) { llama_memory_seq_rm(mem, s, -1, -1) }
        if width > 1 || winner.tokens.count != beams.first?.tokens.count {
            if !llama_memory_seq_rm(mem, 0, Int32(promptLen), -1) {
                // Should not happen for transformer caches; fall back to a full rebuild next time.
                llama_memory_clear(mem, true)
                cached.removeAll()
                throw CompletionError.decodeFailed(-2)
            }
            cached.removeSubrange(promptLen...)
            if !winner.tokens.isEmpty {
                batch.n_tokens = Int32(winner.tokens.count)
                for (j, t) in winner.tokens.enumerated() {
                    batch.token[j] = t
                    batch.pos[j] = Int32(promptLen + j)
                    batch.n_seq_id[j] = 1
                    batch.seq_id[j]![0] = 0
                    batch.logits[j] = j == winner.tokens.count - 1 ? 1 : 0
                }
                let rc = llama_decode(ctx, batch)
                guard rc == 0 else { throw CompletionError.decodeFailed(rc) }
            }
        }
        cached = Array(cached.prefix(promptLen)) + winner.tokens

        // Bail out early on weak or final results.
        if exp(firstWordLogProb) < config.firstWordFloor, !partialWord {
            return SearchOutcome(text: "", stop: .lowConfidence, meanLogProb: 0, firstWordLogProb: firstWordLogProb, alternatives: alternatives, firstTokenMs: firstTokenMs, generatedTokens: generated)
        }
        var out = winner.bytes
        var stop = winner.stop ?? .wordLimit
        if winner.stop != nil || !winner.bytes.starts(with: required) || winner.bytes.count < required.count {
            let text = winner.bytes.count >= required.count ? visibleText(out, requiredCount: required.count) : ""
            return SearchOutcome(text: text, stop: stop, meanLogProb: winner.score, firstWordLogProb: firstWordLogProb, alternatives: alternatives, firstTokenMs: firstTokenMs, generatedTokens: generated)
        }
        if let onPartial { onPartial(visibleText(out, requiredCount: required.count)) }

        // MARK: Phase B — extend greedily.

        var logProbs: [Double] = []
        let maxTokens = request.maxWords * config.tokensPerWord
        let firstWordStillAhead = visibleText(out, requiredCount: required.count).isEmpty
        if firstWordStillAhead { alternatives = [] }
        for step in 0..<maxTokens {
            guard isCurrent(ticket) else { throw CompletionError.cancelled }
            let visible = visibleText(out, requiredCount: required.count)
            if let last = visible.trimmingCharacters(in: .whitespaces).last, TextRules.isSentenceEnd(last),
               TextRules.wordCount(visible) >= request.minWords, !Self.looksLikeAbbreviation(visible) {
                stop = .sentenceEnd
                break
            }
            let d = try distribution(row: -1, bias: bias)
            if step == 0, firstWordStillAhead {
                alternatives = wholeWordAlternatives(d)
            }
            var best = topTokens(d, k: 1, allowed: { _ in true }).first ?? -1
            if best >= 0, table.isEOG[Int(best)] { stop = .endOfText; break }
            if best < 0 || !table.generatable[Int(best)] {
                best = topTokens(d, k: 1, allowed: { self.table.generatable[$0] }).first ?? -1
                if best < 0 { stop = .endOfText; break }
            }
            // No stutter: the same word-level token twice in a row, or any token three times.
            let recent = cached.suffix(2)
            if let last = recent.last, last == best, table.startsWithSpace[Int(best)] || (recent.count == 2 && recent.first == best) {
                stop = .repetition
                break
            }
            var tb = table.bytes[Int(best)]
            var lp = d.logProb(best)
            let words = TextRules.wordCount(visible)
            // A line break in the middle of a phrase usually means the model thinks the text is hard-wrapped.
            // A single-line ghost can't show it, so continue the line instead when that's plausible.
            if request.singleLine, words == 0, table.containsNewline[Int(best)], exp(lp) < 0.7,
               !Self.endsClause(request.text),
               let alt = topTokens(d, k: 1, allowed: { self.table.generatable[$0] && !self.table.containsNewline[$0] }).first,
               exp(d.logProb(alt)) >= config.minBranchProb {
                best = alt
                tb = table.bytes[Int(best)]
                lp = d.logProb(best)
            }
            if table.startsWithBreak[Int(best)] {
                if tb.first == 0x0A || tb.first == 0x0D { stop = .lineEnd; break }
                if words >= request.maxWords { stop = .wordLimit; break }
                let floor = request.confidenceFloor.map { exp($0) } ?? config.wordStartFloor
                if words >= request.minWords, exp(lp) < floor { stop = .lowConfidence; break }
            }
            if table.containsNewline[Int(best)] {
                out.append(contentsOf: tb.prefix { $0 != 0x0A && $0 != 0x0D })
                stop = .lineEnd
                break
            }
            out.append(contentsOf: tb)
            logProbs.append(lp)
            try decodeOne(best)
            generated += 1
            if let onPartial { onPartial(visibleText(out, requiredCount: required.count)) }
            if visibleText(out, requiredCount: required.count).contains("\"\"\"") { stop = .endOfText; break }
        }

        let mean = logProbs.isEmpty ? firstWordLogProb : logProbs.reduce(0, +) / Double(logProbs.count)
        return SearchOutcome(
            text: visibleText(out, requiredCount: required.count),
            stop: stop,
            meanLogProb: mean,
            firstWordLogProb: firstWordLogProb,
            alternatives: alternatives,
            firstTokenMs: firstTokenMs,
            generatedTokens: generated
        )
    }
}
