import AppKit

/// Every item on a pasteboard with every type's data, so the clipboard can be put back exactly as it was.
public struct PasteboardSnapshot: Equatable, Sendable {
    public struct Entry: Equatable, Sendable {
        public var type: String
        public var data: Data
    }

    public struct Item: Equatable, Sendable {
        public var entries: [Entry]
    }

    public var items: [Item]

    public init(items: [Item]) {
        self.items = items
    }

    /// Reads all data now. Types whose data can't be produced (a promise from an app that quit) are skipped.
    public static func capture(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            Item(entries: item.types.compactMap { type in
                item.data(forType: type).map { Entry(type: type.rawValue, data: $0) }
            })
        }
        return PasteboardSnapshot(items: items)
    }

    /// Replaces the pasteboard's contents with the snapshot. Returns the new change count.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let objects = items.map { item -> NSPasteboardItem in
            let object = NSPasteboardItem()
            for entry in item.entries {
                object.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return object
        }
        if !objects.isEmpty { pasteboard.writeObjects(objects) }
        return pasteboard.changeCount
    }
}

/// Marker types from nspasteboard.org that tell clipboard managers to ignore an entry.
public enum PasteboardMarker {
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// Clears the pasteboard and writes `text` marked as transient and auto-generated. Returns the new change count.
    @discardableResult
    public static func writeTransient(_ text: String, to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transient)
        item.setData(Data(), forType: autoGenerated)
        if let bundleID = Bundle.main.bundleIdentifier {
            item.setString(bundleID, forType: source)
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
}
